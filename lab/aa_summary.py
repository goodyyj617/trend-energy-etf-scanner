def picks_table() -> pd.DataFrame:
    return pd.DataFrame([{"순위": p.rank, "조합": p.name, "종류": p.kind, "CAGR": p.cagr, "MDD": p.mdd, "1990년대 MDD": p.sealed_mdd,
                          "비중": p.weights, "앱에서": p.where} for p in PICKS])


def scatter_data() -> pd.DataFrame:
    """CAGR / MDD of the 123 stage-5 candidates (grey) with the picks and the 'not good' ones named."""
    m = pd.read_csv(STAGE5)
    out = pd.DataFrame({"이름": m["이름"], "CAGR": m["cagr"] * 100, "MDD": m["mdd"] * 100, "구분": "다른 후보"})
    names = {p.stage5_name: f"{p.rank} {p.name}" for p in PICKS}
    worse = {"F5 S&P500": "S&P500 100%", "F1 60/40": "60/40", "F3 현재 보유": "현재 보유 (정적)"}
    out.loc[out["이름"].isin(names), "구분"] = "추천"
    out.loc[out["이름"].isin(worse), "구분"] = "기준 미달"
    out["표시"] = out["이름"].map({**names, **worse}).fillna("")
    return out


